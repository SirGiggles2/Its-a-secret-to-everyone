def _build_title_fade_cycles() -> list[list[int]]:
    """Convert each NES 32-byte PALRAM state to 64-word Genesis CRAM."""
    def _cycle_to_cram(nes_pal: list[int]) -> list[int]:
        out = [0] * 64
        for p in range(4):
            for c in range(4):
                out[p*16 + c]     = nes_color_to_gen_cram(nes_pal[p*4 + c])
                out[p*16 + 4 + c] = nes_color_to_gen_cram(nes_pal[16 + p*4 + c])
        return out
    return [_cycle_to_cram(cyc) for cyc in _TITLE_FADE_NES_CYCLES]

def _emit_title_fade(out_path: Path, cycles: list[list[int]],
                     delays: list[int]) -> None:
    """Emit intro_title_fade_cycles[14][64] and intro_title_fade_delays[14]."""
    lines = [
        "/* Auto-generated by tools/extract_intro_assets.py - do not edit. */\n",
        "const unsigned short intro_title_fade_cycles[14][64] = {\n",
    ]
    for i, c in enumerate(cycles):
        lines.append(f"    /* cycle {i} */ {{\n")
        for j in range(0, 64, 8):
            lines.append("        " + ", ".join(f"0x{w:04X}" for w in c[j:j+8]) + ",\n")
        lines.append("    },\n")
    lines.append("};\n\n")
    lines.append("const unsigned short intro_title_fade_delays[14] = {\n    ")
    lines.append(", ".join(str(d) for d in delays))
    lines.append("\n};\n")
    out_path.write_text("".join(lines))

