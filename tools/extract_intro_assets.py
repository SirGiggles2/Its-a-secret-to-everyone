# Path to the nes_full snapshot directory inside tools/intro_demo.
_NES_FULL_DIR = REPO / "tools" / "intro_demo" / "nes_full"

def _read_title_bg_chr() -> bytes:
    """Concatenate CommonBackgroundPatterns + DemoBackgroundPatterns +
    CommonMiscPatterns and convert to Genesis 4bpp (color_shift=0)."""
    ref_dir = REPO / "reference" / "aldonunez" / "dat"
    common = (ref_dir / "CommonBackgroundPatterns.dat").read_bytes()
    demo   = (ref_dir / "DemoBackgroundPatterns.dat").read_bytes()
    misc   = (ref_dir / "CommonMiscPatterns.dat").read_bytes()
    bg_data = common + demo + misc
    n_tiles = len(bg_data) // 16
    gen = bytearray()
    for t in range(n_tiles):
        gen += nes_tile_to_gen_tile(bg_data[t*16:(t+1)*16], color_shift=0)
    return bytes(gen)

def _read_title_sprite_chr() -> bytes:
    """Read chr_title.bin (NES PPU snapshot at title frame, 8 KB), take
    sprite PT0 ($0000-$0FFF), convert 256 tiles to Genesis 4bpp with
    color_shift=4."""
    chr_path = _NES_FULL_DIR / "chr_title.bin"
    chr_data = chr_path.read_bytes()
    if len(chr_data) != 8192:
        raise ValueError(f"chr_title.bin must be 8192 bytes, got {len(chr_data)}")
    sprite_chr = chr_data[0x0000:0x1000]   # PT0 = first 4 KB (256 tiles)
    n_tiles = len(sprite_chr) // 16
    gen = bytearray()
    for t in range(n_tiles):
        gen += nes_tile_to_gen_tile(sprite_chr[t*16:(t+1)*16], color_shift=4)
    return bytes(gen)

def _read_title_palette() -> list[int]:
    """Read palram_title.bin (32-byte NES PALRAM at title frame ~f0100),
    pack into 64-word Genesis CRAM combined layout:
      Gen pal P slots 0-3  = NES BG pal P  (PALRAM $3F00 + P*4)
      Gen pal P slots 4-7  = NES SPR pal P  (PALRAM $3F10 + P*4)
      Gen pal P slots 8-15 = 0 (unused)"""
    pal = (_NES_FULL_DIR / "palram_title.bin").read_bytes()
    if len(pal) != 32:
        raise ValueError(f"palram_title.bin must be 32 bytes, got {len(pal)}")
    cram = [0] * 64
    for p in range(4):
        for c in range(4):
            cram[p*16 + c]     = nes_color_to_gen_cram(pal[p*4 + c])
            cram[p*16 + 4 + c] = nes_color_to_gen_cram(pal[16 + p*4 + c])
    return cram

