def _load_nes_chr(path: Path) -> bytes:
    """Read NES 2bpp CHR blob, convert to Genesis 4bpp, return concatenated bytes."""
    nes = path.read_bytes()
    assert len(nes) % 16 == 0, f"{path}: CHR length not multiple of 16"
    gen = bytearray()
    for i in range(0, len(nes), 16):
        gen += nes_tile_to_gen_tile(nes[i:i+16])
    return bytes(gen)

def _parse_ppu_transfer_records(data: bytes) -> list[tuple[int, bytes]]:
    """Parse a stream of NES PPU transfer records (addr_hi, addr_lo, count, data[count]).

    Trailing $FF byte (or any byte that can't start a valid record) terminates.
    Returns [(addr, payload), ...].
    """
    out: list[tuple[int, bytes]] = []
    i = 0
    while i + 3 <= len(data):
        hi = data[i]
        if hi == 0xFF:
            break
        lo = data[i+1]
        n = data[i+2]
        if i + 3 + n > len(data):
            break
        out.append(((hi << 8) | lo, bytes(data[i+3:i+3+n])))
        i += 3 + n
    return out

def _build_nt1_tilemap(raw: bytes) -> tuple[list[int], int]:
    """Parse an NES PPU transfer record stream that fills NT1 + its attribute
    table, fold the attribute bits into per-cell palette indices, and return
    Genesis nametable words.

    Each NES attribute byte covers a 4x4 tile quad; bits 1:0 = top-left 2x2
    palette, 3:2 = top-right, 5:4 = bottom-left, 7:6 = bottom-right.
    Genesis cell word: (palette << 13) | tile_idx.

    Records targeting NT2 ($2800+) are ignored — they describe rows only the
    NES runtime composer reaches, and the native rewrite handles scroll past
    row 29 separately.
    """
    records = _parse_ppu_transfer_records(raw)

    ROWS = 30
    COLS = 32
    tiles = [0] * (ROWS * COLS)
    attrs = [0] * 64  # NT1 attribute table is 64 bytes

    for addr, payload in records:
        if 0x2000 <= addr < 0x23C0:
            off = addr - 0x2000
            for k, b in enumerate(payload):
                idx = off + k
                if idx < len(tiles):
                    tiles[idx] = b
        elif 0x23C0 <= addr < 0x2400:
            off = addr - 0x23C0
            for k, b in enumerate(payload):
                if off + k < len(attrs):
                    attrs[off + k] = b
        # Records into NT2 ($2800+) describe rows that only become visible
        # via runtime composition on the NES; the native rewrite handles
        # scroll past row 29 separately and ignores them here.

    def _pal_for_cell(r: int, c: int) -> int:
        attr_idx = (r // 4) * 8 + (c // 4)
        quad_row = (r >> 1) & 1
        quad_col = (c >> 1) & 1
        shift = (quad_row * 2 + quad_col) * 2
        return (attrs[attr_idx] >> shift) & 3

    cells = [0] * (ROWS * COLS)
    for r in range(ROWS):
        for c in range(COLS):
            tile = tiles[r * COLS + c]
            pal = _pal_for_cell(r, c)
            cells[r * COLS + c] = ((pal & 3) << 13) | (tile & 0x7FF)
    return cells, ROWS

def _build_story_tilemap(ref_dir: Path) -> tuple[list[int], int]:
    raw = (ref_dir / "StoryTileAttrTransferBuf.dat").read_bytes()
    return _build_nt1_tilemap(raw)

def _build_showcase_tilemap(ref_dir: Path) -> tuple[list[int], int]:
    raw = (ref_dir / "GameTitleTransferBuf.dat").read_bytes()
    return _build_nt1_tilemap(raw)

