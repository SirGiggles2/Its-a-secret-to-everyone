#!/usr/bin/env python3
"""Emit Triforce glow cycle: 8 NES colors converted to Gen CRAM, with
per-step delays (6 frames typical, 16 at final entry per Z_02.asm:976-983).

NES patches PALRAM $3F06 = BG pal 1 color 2. Genesis equivalent =
Gen pal 1 slot 2.

Output: intro_title_glow.c with intro_title_glow_colors[8] +
intro_title_glow_delays[8].
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))
from extract_intro_assets import nes_color_to_gen_cram

OUT = Path(__file__).parent / "intro_title_glow.c"

# Z_02.asm:947 TriforceGlowingColors
NES_GLOW = [0x27, 0x37, 0x37, 0x27, 0x17, 0x07, 0x07, 0x17]
# Z_02.asm:976-983: 6 frames per color, 16 frames at final entry.
DELAYS   = [6, 6, 6, 6, 6, 6, 6, 16]

def main() -> int:
    gen = [nes_color_to_gen_cram(c) for c in NES_GLOW]
    lines = [
        "/* Auto-generated by tools/intro_demo/extract_title_glow.py */\n",
        "/* Triforce glow cycle: 8 NES colors -> Gen CRAM. Per-step delays\n",
        " * (6 frames typical, 16 at final entry per Z_02.asm:976-983).\n",
        " * Patches Gen pal 1 slot 2 (= NES BG pal 1 color 2 / PALRAM $3F06). */\n",
        "const unsigned short intro_title_glow_colors[8] = {\n    ",
    ]
    lines.append(", ".join(f"0x{w:04X}" for w in gen))
    lines.append("\n};\n")
    lines.append("const unsigned char intro_title_glow_delays[8] = {\n    ")
    lines.append(", ".join(str(d) for d in DELAYS))
    lines.append("\n};\n")
    OUT.write_text("".join(lines))
    print(f"wrote {OUT}")
    print("Glow Gen CRAM:", [f"0x{w:04X}" for w in gen])
    return 0

if __name__ == "__main__":
    sys.exit(main())
