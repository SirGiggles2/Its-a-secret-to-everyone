#!/usr/bin/env python3
"""Convert NES PALRAM dump (32 bytes) to Genesis CRAM layout for treasures.

Layout in output:
  Gen pal 0 (CRAM 0-15)  = NES BG pal 0  (text white-on-black)
  Gen pal 1 (CRAM 16-31) = NES sprite pal 0
  Gen pal 2 (CRAM 32-47) = NES sprite pal 1
  Gen pal 3 (CRAM 48-63) = NES sprite pal 2

Each Genesis palette has 16 color slots; only first 4 are used (NES uses
4 colors per palette). Slots 4-15 = $0000 (black).

NES color $00-$3F -> Genesis 9-bit RGB via the same quantizer as
extract_intro_assets.nes_color_to_gen_cram.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

from extract_intro_assets import nes_color_to_gen_cram, NES_PALETTE_RGB  # noqa: F401

DUMP = Path(__file__).parent / "nes_full" / "palram_3380.bin"
OUT  = Path(__file__).parent / "intro_treasures_palette.c"

def build_cram(palram: bytes) -> list[int]:
    """Build 64-word Genesis CRAM."""
    cram = [0x0000] * 64
    # NES BG pal 0 -> Gen pal 0
    for c in range(4):
        cram[c] = nes_color_to_gen_cram(palram[c])
    # NES sprite pal 0/1/2 -> Gen pal 1/2/3
    for sp in range(3):
        for c in range(4):
            nes_color = palram[16 + sp * 4 + c]
            cram[(sp + 1) * 16 + c] = nes_color_to_gen_cram(nes_color)
    return cram

def emit_c(cram: list[int], path: Path):
    lines = ["/* Auto-generated by tools/intro_demo/extract_treasures_palette.py */\n",
             "/* Layout: pal 0 = NES BG pal 0 (text); pal 1/2/3 = NES sprite pal 0/1/2 */\n",
             "const unsigned short intro_treasures_palette[64] = {\n"]
    for i in range(0, 64, 8):
        row = ", ".join(f"0x{w:04X}" for w in cram[i:i+8])
        lines.append(f"    {row},\n")
    lines.append("};\n")
    path.write_text("".join(lines))
    print(f"wrote {path}")

def main():
    palram = DUMP.read_bytes()
    if len(palram) != 32:
        print(f"error: expected 32-byte palram, got {len(palram)}", file=sys.stderr)
        return 2
    cram = build_cram(palram)
    print("Genesis CRAM (first 4 of each palette):")
    for p in range(4):
        print(f"  pal {p}: " + " ".join(f"0x{cram[p*16+c]:04X}" for c in range(4)))
    emit_c(cram, OUT)
    return 0

if __name__ == "__main__":
    sys.exit(main())
