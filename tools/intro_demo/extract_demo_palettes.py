# DemoPhase0Subphase1Delays: $08,$08,$06,$05,$04,$03,$02,$02,$02,$C0,$06,$04,$C0,$03
DELAYS = [0x08, 0x08, 0x06, 0x05, 0x04, 0x03, 0x02, 0x02,
          0x02, 0xC0, 0x06, 0x04, 0xC0, 0x03]

def main() -> int:
    assert len(NES_CYCLES) == 14
    assert len(DELAYS) == 14
    # 12 Gen-CRAM words per cycle: pal1[4..7], pal2[4..7], pal3[4..7].
    # NES bytes 16-19 = sprite pal 0 -> Gen pal 1 slots 4-7
    #          20-23 = sprite pal 1 -> Gen pal 2
    #          24-27 = sprite pal 2 -> Gen pal 3
    #          28-31 = sprite pal 3 (unused, ignored)
    cycles_gen = []
    for nes in NES_CYCLES:
        words = []
        for sp in range(3):
            for c in range(4):
                words.append(nes_color_to_gen_cram(nes[16 + sp*4 + c]))
        cycles_gen.append(words)

    lines = ["/* Auto-generated by tools/intro_demo/extract_demo_palettes.py */\n",
             "/* 14 cycles x 12 Gen CRAM words. Per cycle: pal1[4..7], pal2[4..7], pal3[4..7]. */\n",
             "const unsigned short intro_demo_palette_cycles[14][12] = {\n"]
    for i, words in enumerate(cycles_gen):
        line = "    { " + ", ".join(f"0x{w:04X}" for w in words) + f" }},  /* cycle {i} */\n"
        lines.append(line)
    lines.append("};\n\n")
    lines.append("const unsigned char intro_demo_palette_delays[14] = {\n    ")
    lines.append(", ".join(f"0x{d:02X}" for d in DELAYS))
    lines.append("\n};\n")
    OUT.write_text("".join(lines))
    print(f"wrote {OUT}: 14 cycles, 12 words each")
    return 0

if __name__ == "__main__":
    sys.exit(main())
