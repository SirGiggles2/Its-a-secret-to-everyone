# Compressed delays summing to 230 frames (NES sum is 437; measured
# visible fade f0555 -> f0785 is ~230). Hand-tuned to keep the long
# $C0 holds proportionally larger than the short transitions.
DELAYS = [36, 26, 19, 16, 13, 9, 6, 6, 6, 26, 19, 13, 26, 9]
assert sum(DELAYS) == 230, f"DELAYS sum={sum(DELAYS)}"

def cycle_to_cram(nes_pal):
    """NES 32-byte PALRAM state -> 64-word Gen CRAM in combined layout."""
    out = [0] * 64
    for p in range(4):
        for c in range(4):
            out[p*16 + c]     = nes_color_to_gen_cram(nes_pal[p*4 + c])
            out[p*16 + 4 + c] = nes_color_to_gen_cram(nes_pal[16 + p*4 + c])
    return out

def main() -> int:
    cycles = [cycle_to_cram(c) for c in NES_CYCLES]
    lines = [
        "/* Auto-generated by tools/intro_demo/extract_title_fade.py */\n",
        "/* 14-cycle title fade-out: NES DemoPhase0Subphase1 palette progression\n",
        " * with compressed Gen delays (sum=230 frames vs NES 437) to match the\n",
        " * measured visible fade interval f0555 -> f0785. */\n",
        "const unsigned short intro_title_fade_cycles[14][64] = {\n",
    ]
    for i, c in enumerate(cycles):
        lines.append(f"    /* cycle {i} */ {{\n")
        for j in range(0, 64, 8):
            lines.append("        " + ", ".join(f"0x{w:04X}" for w in c[j:j+8]) + ",\n")
        lines.append("    },\n")
    lines.append("};\n\n")
    lines.append("const unsigned short intro_title_fade_delays[14] = {\n    ")
    lines.append(", ".join(str(d) for d in DELAYS))
    lines.append("\n};\n")
    OUT.write_text("".join(lines))
    print(f"wrote {OUT}: 14 cycles, compressed delays sum={sum(DELAYS)}")
    return 0

